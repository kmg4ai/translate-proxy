def load_dotenv(path=None):
    """Load KEY=VALUE pairs from a .env file into os.environ. Stdlib, no deps.

    Lets users keep API keys in a gitignored .env file instead of exporting
    them: create .env, paste your keys, run. Real environment variables always
    win — a key already set in the shell is never overwritten. A missing file
    is fine (no-op). Looked up next to this script, then in the current
    directory; an absolute path is used as-is.
    """
    target = _find_env_file(path)
    if target is None:
        return
    try:
        with open(target, encoding="utf-8") as f:
            _apply_dotenv(f.read())
    except OSError:
        return


def _env_candidates(path):
    if path is None:
        path = ".env"
    if os.path.isabs(path):
        return [path]
    script_dir = os.path.dirname(os.path.abspath(__file__))
    return [os.path.join(script_dir, path), os.path.join(os.getcwd(), path)]


def _find_env_file(path):
    return next((c for c in _env_candidates(path) if os.path.isfile(c)), None)


def _parse_dotenv(text):
    """Yield (key, value) pairs from .env text.

    Skips blank lines and # comments; tolerates an `export ` prefix, single or
    double quotes around the value, and a trailing ` # comment`.
    """
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):].lstrip()
        key, sep, value = line.partition("=")
        key = key.strip()
        if not sep or not key:
            continue
        value = value.strip()
        if value.startswith("#"):  # KEY=  # comment -> empty value
            value = ""
        elif len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
            value = value[1:-1]  # quoted value, kept as-is
        else:
            comment = value.find(" #")
            if comment != -1:
                value = value[:comment].rstrip()
        yield key, value


def _apply_dotenv(text):
    for key, value in _parse_dotenv(text):
        if key not in os.environ:
            os.environ[key] = value


