def _ensure_env_file(path=".env", dest_dir=None):
    """Create .env from the shipped template when neither .env nor .env.enc exists.

    First run of the proxy makes the file for you — you only paste keys. Returns
    the created path, or None when .env already exists, an encrypted .env is in
    place (a plaintext beside it would defeat it), or creation fails.
    """
    if _find_env_file(path) is not None:
        return None
    if _find_env_file(_ENV_ENC_FILE) is not None:
        return None
    if os.path.isfile(_ENV_TEMPLATE):
        try:
            with open(_ENV_TEMPLATE, encoding="utf-8") as f:
                content = f.read()
        except OSError:
            content = _DEFAULT_ENV_TEMPLATE
    else:
        content = _DEFAULT_ENV_TEMPLATE
    dest = os.path.join(dest_dir or _script_dir(), path)
    try:
        with open(dest, "w", encoding="utf-8") as f:
            f.write(content)
    except OSError:
        return None
    return dest


def _fernet_key(passphrase, salt):
    kdf = PBKDF2HMAC(
        algorithm=hashes.SHA256(), length=32, salt=salt, iterations=_PBKDF2_ITERATIONS
    )
    return Fernet(base64.urlsafe_b64encode(kdf.derive(passphrase.encode("utf-8"))))


def _hash_passphrase(passphrase, salt):
    """One-way PBKDF2-HMAC-SHA256 hash of the passphrase — stored for
    verification only, so a leaked .env.enc still cannot reveal the passphrase."""
    return hashlib.pbkdf2_hmac("sha256", passphrase.encode("utf-8"), salt, _PBKDF2_ITERATIONS)


def _serialize_env_enc(verif_salt, verif_hash, enc_salt, token):
    return (verif_salt.hex() + ":" + verif_hash.hex()
            + ":" + enc_salt.hex() + ":" + token.decode("ascii"))


def _parse_env_enc(payload):
    parts = payload.split(":")
    if len(parts) < 4:
        raise ValueError("corrupted .env.enc")
    return (bytes.fromhex(parts[0]), parts[1],
            bytes.fromhex(parts[2]), ":".join(parts[3:]).encode("ascii"))


def _decrypt_env_enc_payload(payload, passphrase):
    """Verify the passphrase against its stored hash, then Fernet-decrypt."""
    verif_salt, verif_hash, enc_salt, token = _parse_env_enc(payload)
    if not hmac.compare_digest(_hash_passphrase(passphrase, verif_salt).hex(), verif_hash):
        raise ValueError("wrong passphrase — could not decrypt .env.enc")
    try:
        return _fernet_key(passphrase, enc_salt).decrypt(token)
    except InvalidToken:
        raise ValueError("wrong passphrase — could not decrypt .env.enc")


def _passphrase(confirm=False):
    pw = os.environ.get(_ENV_PASSPHRASE_VAR)
    if pw:
        return pw
    import getpass
    if confirm:
        pw1 = getpass.getpass("passphrase for .env.enc: ")
        pw2 = getpass.getpass("repeat passphrase: ")
        if pw1 != pw2:
            raise ValueError("passphrases do not match")
        return pw1
    return getpass.getpass("passphrase: ")


def encrypt_env_file(src=".env", dst=_ENV_ENC_FILE):
    """Encrypt a plaintext .env into dst (Fernet + PBKDF2-SHA256, 600k iters).

    The passphrase is never stored: a PBKDF2 hash is written for verification
    and the Fernet key is derived from the passphrase at decrypt time. The
    source file is left untouched — after verifying the proxy starts, remove
    it yourself so no plaintext remains.
    """
    if not _HAVE_CRYPTO:
        raise RuntimeError("--make-env-enc needs `pip install cryptography` (optional)")
    if not os.path.isfile(src):
        raise FileNotFoundError(f"no {src} to encrypt")
    with open(src, encoding="utf-8") as f:
        plaintext = f.read()
    pw = _passphrase(confirm=True)
    verif_salt = os.urandom(16)
    verif_hash = _hash_passphrase(pw, verif_salt)
    enc_salt = os.urandom(16)
    token = _fernet_key(pw, enc_salt).encrypt(plaintext.encode("utf-8"))
    with open(dst, "w", encoding="utf-8") as f:
        f.write(f"# {dst} — encrypted .env (Fernet + PBKDF2). Unlock with {_ENV_PASSPHRASE_VAR}.\n")
        f.write(_serialize_env_enc(verif_salt, verif_hash, enc_salt, token) + "\n")
    return dst


def decrypt_env_file(src=_ENV_ENC_FILE, dst=".env"):
    """Decrypt src back to plaintext dst (for editing keys)."""
    if not _HAVE_CRYPTO:
        raise RuntimeError("--env-decrypt needs `pip install cryptography` (optional)")
    if not os.path.isfile(src):
        raise FileNotFoundError(f"no {src} to decrypt")
    with open(src, encoding="utf-8") as f:
        payload = next((ln for ln in f.read().splitlines() if ln.strip() and not ln.startswith("#")), "")
    plaintext = _decrypt_env_enc_payload(payload, _passphrase())
    with open(dst, "w", encoding="utf-8") as f:
        f.write(plaintext.decode("utf-8"))
    return dst


def _load_dotenv_enc(path=_ENV_ENC_FILE):
    """Decrypt .env.enc into os.environ in memory — never writes plaintext.

    Only meaningful when there is no plaintext .env. A daemon cannot prompt
    interactively, so it needs ENV_PASSPHRASE set. Wrong passphrase -> warning
    and skip (the proxy still starts; keys are simply absent).
    """
    if not _HAVE_CRYPTO:
        return
    target = _find_env_file(path)
    if target is None:
        return
    try:
        with open(target, encoding="utf-8") as f:
            payload = next((ln for ln in f.read().splitlines() if ln.strip() and not ln.startswith("#")), "")
    except OSError:
        return
    passphrase = os.environ.get(_ENV_PASSPHRASE_VAR)
    if not passphrase:
        print(f"[translate-proxy] warning: {target} found but {_ENV_PASSPHRASE_VAR} "
              "is not set — not loading it", file=sys.stderr)
        return
    try:
        plaintext = _decrypt_env_enc_payload(payload, passphrase)
    except ValueError as e:
        print(f"[translate-proxy] warning: {target} could not be decrypted ({e})", file=sys.stderr)
        return
    _apply_dotenv(plaintext.decode("utf-8"))


